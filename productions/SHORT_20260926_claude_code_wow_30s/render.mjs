import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const folder=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(folder,'../..'), studio=path.join(root,'studio');
const require=createRequire(path.join(studio,'package.json'));
const {bundle}=require('@remotion/bundler');
const {selectComposition,renderMedia,renderStill}=require('@remotion/renderer');
const {chromium}=require('playwright');
const out=path.resolve(process.argv[2]);
if(!out.startsWith(path.join(root,'outputs/productions',path.basename(folder))+path.sep))throw Error('Expected this production output');
const record=async p=>({path:path.relative(root,p).replaceAll('\\','/'),bytes:(await fs.stat(p)).size,sha256:createHash('sha256').update(await fs.readFile(p)).digest('hex').toUpperCase()});
const check=async r=>{const p=path.resolve(root,r.path);if(!p.startsWith(root+path.sep))throw Error('Outside workspace');const a=await record(p);if(a.bytes!==r.bytes||a.sha256!==r.sha256)throw Error('Changed input '+r.path);return p;};
const prep=JSON.parse(await fs.readFile(path.join(out,'preparation.json'),'utf8'));
for(const r of prep.sources)await check(r);
const sources=[...prep.sources,...await Promise.all(['src/remotion/ScreenTypography.tsx','public/template-assets/NotoSansJP-Variable.ttf','package.json','package-lock.json'].map(n=>record(path.join(studio,n))))];
const pub=path.join(out,'public');await fs.mkdir(path.join(pub,'template-assets'),{recursive:true});
await fs.copyFile(path.join(studio,'public/template-assets/NotoSansJP-Variable.ttf'),path.join(pub,'template-assets/NotoSansJP-Variable.ttf'));
const probe=p=>JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',p],{encoding:'utf8',windowsHide:true}));
for(const [key,item] of Object.entries(prep.story.visuals)){
  const source=path.join(root,item.path), v=probe(source).streams.find(s=>s.codec_type==='video');
  if(v.width<768||v.height<1344||v.avg_frame_rate!=='24/1'||Number(v.nb_frames)<120)throw Error('Insufficient source');
  execFileSync('ffmpeg',['-v','error','-xerror','-i',source,'-f','null','-'],{windowsHide:true});
  await fs.copyFile(source,path.join(pub,key+'.mp4'));
}
const text=await fs.readFile(path.join(folder,'Wow.tsx'),'utf8');
const sizes=[...text.matchAll(/fontSize:\s*(\d+)/g),...text.matchAll(/size=\{(\d+)\}/g)].map(m=>Number(m[1]));
if(Math.min(...sizes)<54)throw Error('Font floor');
const browserExecutable=chromium.executablePath();
const inputProps={segments:prep.story.segments,captions:true};
const serveUrl=await bundle({entryPoint:path.join(folder,'Wow.tsx'),rootDir:studio,publicDir:pub,outDir:path.join(out,'bundle'),webpackOverride:c=>({...c,resolve:{...c.resolve,modules:[path.join(studio,'node_modules'),...(c.resolve?.modules??[])]}})});
const composition=await selectComposition({serveUrl,id:'ClaudeWow30',browserExecutable,inputProps});
for(const frame of [72,192,312,432,552,672])await renderStill({composition,serveUrl,browserExecutable,inputProps,frame,imageFormat:'png',output:path.join(out,`design-${frame}.png`),overwrite:false});
console.log(JSON.stringify({event:'stills_ready',out}));
const file=path.join(out,'timeline-silent.mp4');let last=-1;
await renderMedia({composition,serveUrl,browserExecutable,inputProps,outputLocation:file,codec:'h264',pixelFormat:'yuv420p',colorSpace:'bt709',imageFormat:'png',crf:14,muted:true,concurrency:2,overwrite:false,onProgress:({progress})=>{const p=Math.floor(progress*10);if(p>last){last=p;console.log(JSON.stringify({event:'render',percent:p*10}));}}});
const result=probe(file),v=result.streams[0];
if(result.streams.length!==1||v.width!==1080||v.height!==1920||v.avg_frame_rate!=='24/1'||Number(v.nb_frames)!==720||Number(result.format.duration)!==30)throw Error('Output format');
execFileSync('ffmpeg',['-v','error','-xerror','-i',file,'-f','null','-'],{windowsHide:true});
for(const r of sources)await check(r);
await fs.writeFile(path.join(out,'render.json'),JSON.stringify({sources,timeline:await record(file),probe:result,full_decode_verified:true,new_video_generation:false,encoding:{crf:14},typography:{minimum_font_px:Math.min(...sizes),at_360px:Math.min(...sizes)/3,sizes:[...new Set(sizes)]}},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({event:'render_complete',out}));
