        for i,(speaker,chapter,text,sources) in enumerate(turns,1):
            spoken=reading(text)
            assert 1<=len(spoken)<=300,(i,len(spoken))
            data['turns'].append(dict(id=f'{kind[0]}{i:02}',speaker=speaker,chapter=chapter,display=text,reading=spoken,source_ids=sources))
        path=HERE/f'{kind}-dialogue-v02-draft.json'
